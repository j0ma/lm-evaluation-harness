"""
Script to generate task YAMLs for the Sami NMT dataset.
Prompt style is passed via command line --task_args, not baked into YAML.
Based on `tasks/translation/utils.py`.
"""

import argparse
import itertools

import yaml
from langcodes import Language

# utils
flatten = lambda l: list(itertools.chain(*l))

# constants
_LANGUAGES = [
    "fin",
    "sme",
]

LANGUAGES_OF_INTEREST = _LANGUAGES

MAIN_LANG = "sme"
LANGUAGE_PAIRS = [("fin", "sme"), ("sme", "fin")]

CORPORA = ["uit", "yle"]
PROMPT_STYLES = ["default", "madlad"]

# auxiliary functions
def code_to_language_name(code):
    return Language.make(language=Language.get(code)["language"]).display_name()


def code_to_short_name(code):
    return Language.get(code)["language"]


jinja_var = (
    lambda s: "{{" + s + "}}"
)  # wrapper to avoid having to escape { } in format strings


def gen_lang_yamls(output_dir: str, overwrite: bool, num_fewshot: int) -> None:
    """
    Generate YAML files for each translation direction.
    Prompt style is NOT baked into the YAML; it's passed via CLI --task_args.
    """

    err = []

    settings_iterable = itertools.product(CORPORA, LANGUAGE_PAIRS, PROMPT_STYLES)
    
    for corpus, (src, tgt), prompt_style in settings_iterable:
        lang_pair_name = f"{src}-{tgt}"
        yaml_file_name = f"saminmt_icl_K{num_fewshot}_{corpus}_{lang_pair_name}_{prompt_style}.yaml"

        try:
            with open(
                f"{output_dir}/{yaml_file_name}",
                "w" if overwrite else "x",
                encoding="utf-8",
            ) as outfile:
                print(f"Creating {yaml_file_name}...")
                outfile.write("# File generated by `create_yamls_saminmt.py`\n")
                yaml.safe_dump(
                    {
                        "include": "_saminmt_common_yaml",
                        "task": f"saminmt_icl_K{num_fewshot}_{corpus}_{lang_pair_name}_{prompt_style}",
                        "corpus": corpus,
                        "source_language_code": src,
                        "target_language_code": tgt,
                        "prompt_style": prompt_style,
                        "num_fewshot": num_fewshot
                    },
                    outfile,
                    sort_keys=False,
                    default_style=None,
                    default_flow_style=False,
                )

        except FileExistsError:
            err.append(yaml_file_name)

        if len(err) > 0:
            raise FileExistsError(
                "Files were not created because they already exist:"
                f" {', '.join(err)}"
                "\nUse flag --overwrite to overwrite them."
            )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--overwrite",
        default=False,
        action="store_true",
        help="Overwrite files if they already exist",
    )
    parser.add_argument(
        "--output-dir", default=".", help="Directory to write yaml files to"
    )
    parser.add_argument(
        "--num-fewshot", default=1, help="Number of few-shot examples"
    )
    args = parser.parse_args()

    gen_lang_yamls(output_dir=args.output_dir, overwrite=args.overwrite, num_fewshot=args.num_fewshot)


if __name__ == "__main__":
    main()
